"""Author the original bounded CBOR sequence grid as native function checks.

The local host model counts supported items, not telemetry records. Publication
prose is directly edited LaTeX and is never generated by this module.
"""

import argparse
import json
from pathlib import Path
from function_lesson_cases import bits

MASK = (1 << 64) - 1
INVALID = 0x123456780001
ARENAS = {"source": 1280, "record": 256, "destination": 320, "workspace": 8192}
CALLER = {"source": 1280, "record": 256, "destination": 320}
TRACE = bytes.fromhex(
    "b80403a201824280ff21008002980a00181718182037381818ff190100197fff397fff01580300ff4118001b0102030405060708"
)


def head(raw, at):
    if not 0 <= at < len(raw):
        raise ValueError("Missing head")
    initial = raw[at]
    kind = initial >> 5
    info = initial & 31
    if kind not in (0, 1, 2, 4, 5) or info >= 28:
        raise ValueError("Unsupported local head")
    if info < 24:
        return kind, info, at + 1
    width = 1 << (info - 24)
    if len(raw) - at - 1 < width:
        raise ValueError("Truncated argument")
    return kind, int.from_bytes(raw[at + 1 : at + 1 + width], "big"), at + 1 + width


def value_end(raw, at, depth):
    kind, arg, cursor = head(raw, at)
    if kind in (0, 1):
        return cursor
    if kind == 2:
        if arg > 32 or arg > len(raw) - cursor:
            raise ValueError("Byte string bound")
        return cursor + arg
    if depth >= 8:
        raise ValueError("Container depth")
    if kind == 4:
        if arg > 64:
            raise ValueError("Array bound")
        for _ in range(arg):
            cursor = value_end(raw, cursor, depth + 1)
    else:
        if arg > 8:
            raise ValueError("Map bound")
        seen = 0
        for _ in range(arg):
            key, number, cursor = head(raw, cursor)
            if key != 0 or number >= 8 or seen & (1 << number):
                raise ValueError("Map key identity")
            seen |= 1 << number
            cursor = value_end(raw, cursor, depth + 1)
    return cursor


def sequence_count(raw, depth):
    cursor = 0
    items = 0
    while cursor < len(raw):
        cursor = value_end(raw, cursor, depth)
        items += 1
    if cursor != len(raw):
        raise ValueError("Exact selected extent")
    return items


def trials():
    document = json.loads(
        Path(__file__).with_name("cbor_sequence_samples.json").read_text()
    )
    if document["formatVersion"] != 1:
        raise ValueError("Unsupported finite sequence grid")
    return [
        {
            **row,
            "data": bytes.fromhex(row["bytes"]),
            "depth": int(row["depth"]),
            "count": int(row["count"]),
        }
        for row in document["cases"]
    ]


def outcome(row):
    if row["count"] > 1024:
        return 2, 0
    if row["depth"] > 8:
        return 1, 0
    logical = (row["data"] + bytes([165]) * row["count"])[: row["count"]]
    try:
        return 0, sequence_count(logical, row["depth"])
    except ValueError:
        return 1, 0


def setup(row):
    memory = {name: bytes([165]) * size for name, size in ARENAS.items()}
    source = bytearray(memory["source"])
    at = row["offset"]
    source[at : at + len(row["data"])] = row["data"]
    memory["source"] = bytes(source)
    return memory


def preserved():
    return {
        **{f"s{i}": bits(0x3456789A00000000 + 733 * i) for i in range(8)},
        "fp": bits(0x3456789A00000000 + 733 * 8),
    }


def address(label, offset=0):
    return dict(label=label, offset=offset)


def window(label, offset, length):
    return dict(at=address(label, offset), length=length)


def call(row, memory):
    status, count = outcome(row)
    early = row["count"] > 1024 or row["depth"] > 8 or row["count"] == 0
    reads = [] if early else [window("source", row["offset"], row["count"])]
    args = {"a1": bits(row["count"]), "a2": bits(row["depth"])}
    result = dict(
        entry="cbor_sequence_count",
        returnTo="function_return",
        arguments=args,
        expectedRegisters={"v0": bits(status), "v1": bits(count)},
        expectedAddresses={"sp": address("workspace", 8192)},
        memory=[dict(label=name, bytes=memory[name].hex()) for name in CALLER],
        accessPolicies=[
            dict(
                **{"from": address(name), "until": address(name, size)},
                readable=reads,
                writable=[],
                maxAccesses=500000,
            )
            for name, size in CALLER.items()
        ],
        accessHistory=dict(
            regions=[window("source", 0, 1280), window("workspace", 0, 8192)],
            maxAccesses=500000,
        ),
    )
    if early:
        args["a0"] = bits(INVALID)
    else:
        result["argumentAddresses"] = {"a0": address("source", row["offset"])}
    return result


def definition(row):
    memory = setup(row)
    saved = preserved()
    return dict(
        name=row["name"],
        instructionLimit=row["instructionLimit"],
        calls=[call(row, memory)],
        initialRegisters=saved,
        preservedRegisters=list(saved),
        callerStackBytes=0,
        stackAlignment=16,
        initialRegisterAddresses={"sp": address("workspace", 8192)},
        initialMemory=[
            dict(label=name, bytes=value.hex()) for name, value in memory.items()
        ],
    )


def supplemental():
    caller = dict(
        name="complete supplied sequence caller",
        instructionLimit=4000000,
        callerStackBytes=0,
        initialRegisterAddresses={"sp": address("workspace", 8192)},
        calls=[
            dict(
                entry="main",
                returnTo="sequence_return",
                arguments={},
                expectedRegisters={"v0": bits(0), "v1": bits(1)},
            )
        ],
        exit=dict(
            code=0,
            memory=[
                dict(label="status", bytes="00000000"),
                dict(label="count", bytes="0100000000000000"),
            ],
        ),
    )
    row = dict(
        name="same-session rejection success empty and inherited-depth failure",
        instructionLimit=4000000,
        data=bytes.fromhex("ff808180"),
        offset=0,
        count=1,
        depth=0,
    )
    retry = definition(row)
    memory = setup(row)
    retry["calls"] = [
        call(
            {
                **row,
                "offset": offset,
                "data": row["data"][offset:],
                "count": count,
                "depth": depth,
            },
            memory,
        )
        for offset, count, depth in [(0, 1, 0), (1, 1, 7), (0, 0, 8), (1, 3, 7)]
    ]
    return {"caller": [caller], "retry": [retry]}


def profiles():
    groups = {}
    for row in trials():
        groups.setdefault(row["group"], []).append(definition(row))
    groups.update(supplemental())
    result = {}
    for group, cases in groups.items():
        batch = []
        part = 0
        for case in cases:
            candidate = batch + [case]
            if batch and (
                sum(c["instructionLimit"] for c in candidate) > 10000000
                or len(
                    json.dumps(
                        dict(formatVersion=14, cases=candidate), separators=(",", ":")
                    ).encode()
                )
                + 1
                > 1024 * 1024
            ):
                result[f"cbor-sequence-{group}-{part:03d}.cases.json"] = dict(
                    formatVersion=14, cases=batch
                )
                batch = []
                part += 1
            batch.append(case)
        if batch:
            result[f"cbor-sequence-{group}-{part:03d}.cases.json"] = dict(
                formatVersion=14, cases=batch
            )
    return result


def build(directory, check=False):
    directory = Path(directory)
    if not check:
        directory.mkdir(parents=True, exist_ok=True)
    files = {
        name: json.dumps(value, separators=(",", ":")) + "\n"
        for name, value in profiles().items()
    }
    for name, text in files.items():
        path = directory / name
        if check:
            if not path.is_file() or path.read_text() != text:
                raise ValueError(f"Stale CBOR sequence profile: {path}")
        else:
            path.write_text(text)
    return files


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    build(args.directory, args.check)
